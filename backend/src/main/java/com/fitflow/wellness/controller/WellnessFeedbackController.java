package com.fitflow.wellness.controller;

import com.fitflow.security.UserPrincipal;
import com.fitflow.wellness.WellnessFeedbackService;
import com.fitflow.wellness.dto.AcceptProposalRequest;
import com.fitflow.wellness.dto.ClassFeedbackRequest;
import com.fitflow.wellness.dto.FeedbackResponse;
import com.fitflow.wellness.dto.RestrictionProposalDto;
import com.fitflow.wellness.dto.WeeklyProgressResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.time.LocalDate;
import java.util.List;

@RestController
@RequiredArgsConstructor
@Tag(name = "Wellness Feedback & Progress", description = "Workout progress tracking, attended class feedback, pain detection, and restriction proposals")
public class WellnessFeedbackController {

    private final WellnessFeedbackService feedbackService;

    @GetMapping("/api/v1/wellness/progress/weekly")
    @PreAuthorize("hasRole('MEMBER')")
    @Operation(summary = "Get weekly booking counts, attendance, streak weeks, and calorie expenditure")
    public ResponseEntity<WeeklyProgressResponse> getWeeklyProgress(
            @AuthenticationPrincipal UserPrincipal principal,
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate weekStart) {
        return ResponseEntity.ok(feedbackService.getWeeklyProgress(principal.getId(), weekStart));
    }

    @PostMapping("/api/v1/bookings/{bookingId}/feedback")
    @PreAuthorize("hasRole('MEMBER')")
    @Operation(summary = "Submit post-session rating, encrypted comments, and report pain symptoms")
    public ResponseEntity<FeedbackResponse> submitFeedback(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable Long bookingId,
            @Valid @RequestBody ClassFeedbackRequest request) {
        return ResponseEntity.ok(feedbackService.submitFeedback(principal.getId(), bookingId, request));
    }

    @GetMapping("/api/v1/wellness/restriction-proposals")
    @PreAuthorize("hasRole('MEMBER')")
    @Operation(summary = "Get pending movement restriction proposals generated by pain feedback")
    public ResponseEntity<List<RestrictionProposalDto>> getProposals(
            @AuthenticationPrincipal UserPrincipal principal) {
        return ResponseEntity.ok(feedbackService.getProposals(principal.getId()));
    }

    @PostMapping("/api/v1/wellness/restriction-proposals/{id}/accept")
    @PreAuthorize("hasRole('MEMBER')")
    @Operation(summary = "Explicitly accept a restriction proposal and raise health profile injury severity")
    public ResponseEntity<RestrictionProposalDto> acceptProposal(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable Long id,
            @Valid @RequestBody AcceptProposalRequest request) {
        return ResponseEntity.ok(feedbackService.acceptProposal(principal.getId(), id, request));
    }

    @PostMapping("/api/v1/wellness/restriction-proposals/{id}/dismiss")
    @PreAuthorize("hasRole('MEMBER')")
    @Operation(summary = "Dismiss a pending movement restriction proposal")
    public ResponseEntity<RestrictionProposalDto> dismissProposal(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable Long id) {
        return ResponseEntity.ok(feedbackService.dismissProposal(principal.getId(), id));
    }
}
